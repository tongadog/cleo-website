#!/usr/bin/env python3
"""Build the on-site reader data from content/articles/manifest.json.

Only articles with status "collected" get a reader page. Everything else
(needs_review, unavailable) keeps linking out to FDD / the publisher.

Outputs:
  reader-index.js           window.READER = {fddUrl: {slug, kind}}  (small, loaded by index.html)
  content/reader/<slug>.json  {meta..., kind: "text"|"pdf", html | pdf}

GitHub Pages runs Jekyll, which swallows .md files with front matter, so the
Markdown is pre-rendered to HTML here instead of being fetched in the browser.

Usage: python3 scripts/build_reader.py
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "content" / "articles" / "manifest.json"
OUT_DIR = ROOT / "content" / "reader"
INDEX_JS = ROOT / "reader-index.js"


def load_articles():
    text = (ROOT / "articles.js").read_text(encoding="utf-8")
    start = text.index("[")
    end = text.rindex("]") + 1
    return json.loads(text[start:end])


URL_RE = re.compile(r"(https?://[^\s<>\"]+[^\s<>\".,;:)\]])")


def inline(text):
    out = html.escape(text, quote=False)
    out = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", out)
    out = URL_RE.sub(r'<a href="\1" target="_blank" rel="noopener">\1</a>', out)
    return out


def render_markdown(md):
    """Tiny renderer for the subset the collectors emit: ##, -, >, **, paragraphs."""
    parts = []
    in_list = False
    for block in [b.strip() for b in re.split(r"\n\s*\n", md) if b.strip()]:
        is_item = block.startswith("- ")
        if in_list and not is_item:
            parts.append("</ul>")
            in_list = False
        if block.startswith("#"):
            level = min(len(block) - len(block.lstrip("#")), 4)
            tag = "h2" if level <= 2 else "h3"
            parts.append(f"<{tag}>{inline(block.lstrip('#').strip())}</{tag}>")
        elif is_item:
            if not in_list:
                parts.append("<ul>")
                in_list = True
            for line in block.split("\n"):
                parts.append(f"<li>{inline(line[2:].strip() if line.startswith('- ') else line.strip())}</li>")
        elif block.startswith(">"):
            body = " ".join(l.lstrip("> ").strip() for l in block.split("\n"))
            parts.append(f"<blockquote><p>{inline(body)}</p></blockquote>")
        else:
            parts.append(f"<p>{inline(' '.join(block.split()))}</p>")
    if in_list:
        parts.append("</ul>")
    return "\n".join(parts)


def strip_frontmatter(text):
    if text.startswith("---"):
        parts = text.split("---\n", 2)
        if len(parts) == 3:
            return parts[2]
    return text


def main():
    articles = {a["url"]: a for a in load_articles()}
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    keep = set()
    index = {}
    for row in manifest:
        if row.get("status") != "collected":
            continue
        art = articles.get(row["fddUrl"])
        if not art:
            continue
        slug = row["slug"]
        data = {
            "slug": slug,
            "title": art["title"],
            "date": art.get("date", ""),
            "outlet": art.get("outlet", ""),
            "category": art.get("category", ""),
            "subtitle": art.get("subtitle", ""),
            "authors": art.get("authors", []),
            "issues": art.get("issues", []),
            "thumbnail": art.get("thumbnail", ""),
            "fddUrl": art["url"],
            "sourceUrl": art.get("sourceUrl", ""),
            "words": row.get("words", 0),
        }
        if row.get("path") and (ROOT / row["path"]).exists():
            md = strip_frontmatter((ROOT / row["path"]).read_text(encoding="utf-8"))
            data.update(kind="text", html=render_markdown(md))
        elif row.get("pdfPath") and (ROOT / row["pdfPath"]).exists():
            data.update(kind="pdf", pdf=row["pdfPath"])
        else:
            continue
        (OUT_DIR / f"{slug}.json").write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
        keep.add(f"{slug}.json")
        index[art["url"]] = {"slug": slug, "kind": data["kind"]}
    for stale in OUT_DIR.glob("*.json"):
        if stale.name not in keep:
            stale.unlink()
    INDEX_JS.write_text(
        "// Generated by scripts/build_reader.py — do not edit by hand.\n"
        "// FDD URL -> on-site reader entry for articles whose full text is collected.\n"
        f"window.READER = {json.dumps(index, ensure_ascii=False, indent=0)};\n",
        encoding="utf-8",
    )
    kinds = {}
    for v in index.values():
        kinds[v["kind"]] = kinds.get(v["kind"], 0) + 1
    print(f"reader entries: {len(index)} {kinds}")


if __name__ == "__main__":
    main()
